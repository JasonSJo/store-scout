import assert from 'node:assert/strict';
import ts from 'typescript';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../lib/phone.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { formatKoreanPhone: f } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
assert.equal(f('01012345678'), '010-1234-5678');
assert.equal(f('010-12a34 5678'), '010-1234-5678');
assert.equal(f('0212345678'), '02-1234-5678');
assert.equal(f('0311234567'), '031-123-4567');
assert.equal(f('010123456789999'), '010-1234-5678');
assert.equal(f(''), '');
console.log('phone formatter: 6 checks passed');
